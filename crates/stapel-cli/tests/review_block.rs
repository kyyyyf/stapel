//! STP-38: the generated block in the Review section of `ticket.md`. Step 1: the block from findings.

mod common;

use common::{repo_with_ticket, stapel};
use serde_json::{Map, Value, json};
use std::path::Path;

const TICKET: &str = ".stapel/tickets/ABC-1/ticket.md";
const FINDINGS: &str = ".stapel/tickets/ABC-1/findings.jsonl";
const BEGIN: &str = "<!-- stapel:review:begin -->";
const END: &str = "<!-- stapel:review:end -->";

fn put(dir: &Path, rel: &str, text: &str) {
    let path = dir.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

fn finding(id: &str, stage: &str, round: u32, role: &str, severity: &str, fate: &str) -> String {
    json!({
        "id": id,
        "ticket": "ABC-1",
        "stage": stage,
        "round": round,
        "role": role,
        "severity": severity,
        "promise": "inside",
        "claim": "a claim",
        "catchable_at": "code",
        "fate": fate,
    })
    .to_string()
}

fn lines(items: &[String]) -> String {
    items.iter().map(|l| format!("{l}\n")).collect()
}

/// The generated block of a `ticket.md` text: its lines from the begin marker to the end marker.
fn block_of(text: &str) -> String {
    let all: Vec<&str> = text.split_inclusive('\n').collect();
    let from = all
        .iter()
        .position(|l| l.trim_end() == BEGIN)
        .expect("no begin marker");
    let to = all
        .iter()
        .position(|l| l.trim_end() == END)
        .expect("no end marker");
    all[from..=to].concat()
}

/// The records of the findings file of ABC-1.
fn records(dir: &Path) -> Vec<Map<String, Value>> {
    common::read(dir, FINDINGS)
        .lines()
        .map(|l| serde_json::from_str::<Value>(l).unwrap())
        .map(|v| v.as_object().unwrap().clone())
        .collect()
}

#[test]
fn import_and_triage_write_the_block() {
    // No finding and no run: both lines say none.
    assert_eq!(
        stapel_core::review_block::render(&[], &[]),
        format!(
            "{BEGIN}\nGenerated by stapel; edits between the markers are overwritten.\n\n\
             Findings: none\n\nCheck runs: none\n{END}\n"
        )
    );

    let repo = repo_with_ticket();
    let dir = repo.path();
    put(
        dir,
        "in.jsonl",
        &lines(&[
            finding("F-1", "spec-review", 1, "external", "LOW", "patch"),
            finding("F-2", "spec-review", 1, "reviewer", "HIGH", "open"),
            finding("F-3", "code-review", 1, "fresh-code", "MEDIUM", "defer"),
            finding("F-4", "code-review", 1, "reviewer", "HIGH", "open"),
            finding("F-5", "code-review", 2, "reviewer", "LOW", "patch"),
        ]),
    );
    stapel(dir)
        .args(["findings", "import", "in.jsonl"])
        .assert()
        .success();
    let after_import = block_of(&common::read(dir, TICKET));

    // F-2 is regraded low, F-4 is false.
    put(
        dir,
        "triage.jsonl",
        &lines(&[
            json!({"id": "F-2", "ticket": "ABC-1", "fate": "patch", "verdict": "low"}).to_string(),
            json!({"id": "F-4", "ticket": "ABC-1", "fate": "no-change", "verdict": "false",
                "evidence": "the code does it"})
            .to_string(),
        ]),
    );
    stapel(dir)
        .args(["findings", "triage", "triage.jsonl"])
        .assert()
        .success();
    let after_triage = block_of(&common::read(dir, TICKET));

    let golden = include_str!("golden/review_block.md");
    assert_eq!(format!("{after_import}\n{after_triage}"), golden);

    // The text outside the block is not touched.
    let text = common::read(dir, TICKET);
    assert!(text.starts_with("# ABC-1"), "{text}");
    assert!(text.contains("## Spec\n\nThe spec.\n"), "{text}");
}

/// A `ticket.md` text whose Review section holds `body`, in the line end `eol`.
fn ticket_with(body: &str, eol: &str) -> String {
    let text = format!(
        "# ABC-1 — First\n\n## Spec\n\nThe spec.\n\n## Design\n\nThe design.\n\n## Proof\n\n\
         The proof.\n\n## Review\n\n{body}## Summary\n\nTODO\n"
    );
    text.replace('\n', eol)
}

/// Imports one finding into a fresh ticket whose `ticket.md` is `text`; returns the new text and
/// the block that `render` makes for the finding.
fn import_into(text: &str) -> (String, String) {
    let repo = repo_with_ticket();
    let dir = repo.path();
    put(dir, TICKET, text);
    put(
        dir,
        "in.jsonl",
        &lines(&[finding("F-1", "spec-review", 1, "reviewer", "HIGH", "open")]),
    );
    stapel(dir)
        .args(["findings", "import", "in.jsonl"])
        .assert()
        .success();
    let block = stapel_core::review_block::render(&records(dir), &[]);
    (common::read(dir, TICKET), block)
}

#[test]
fn keeps_text_outside() {
    // Hand lines before and after an existing block.
    let old = format!("Hand before.\n\n{BEGIN}\nold\n{END}\n\nHand after.\n\n");
    let (text, block) = import_into(&ticket_with(&old, "\n"));
    let want = format!("Hand before.\n\n{block}\nHand after.\n\n");
    assert_eq!(text, ticket_with(&want, "\n"));

    // No block: it follows the last non-empty line after one empty line; the trailing empty
    // lines of the section stay after it.
    let (text, block) = import_into(&ticket_with("Hand line.\n\n\n", "\n"));
    assert_eq!(text, ticket_with(&format!("Hand line.\n\n{block}\n\n"), "\n"));

    // Removing the block gives the text back.
    let without = text.replace(&format!("\n{block}"), "");
    assert_eq!(without, ticket_with("Hand line.\n\n\n", "\n"));

    // A CRLF file with a block, markers with trailing spaces: replaced, CRLF kept.
    let old = format!("Hand before.\n\n{BEGIN}  \nold\n{END} \n\nHand after.\n\n");
    let (text, block) = import_into(&ticket_with(&old, "\r\n"));
    let want = format!("Hand before.\n\n{block}\nHand after.\n\n");
    assert_eq!(text, ticket_with(&want, "\r\n"));

    // A CRLF file without a block: the block takes the line end of the first line.
    let (text, block) = import_into(&ticket_with("Hand line.\n\n", "\r\n"));
    assert_eq!(text, ticket_with(&format!("Hand line.\n\n{block}\n"), "\r\n"));
}
