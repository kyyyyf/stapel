//! STP-38: the generated block of the Review section of `ticket.md`: its text (`render`), its place
//! between two marker lines (`place`) and its write (`write`).

use crate::journal::{self, Entry};
use crate::records::STAGES;
use crate::ticket;
use crate::triage::{state_of, whole_round};
use serde_json::{Map, Value};
use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

pub const BEGIN: &str = "<!-- stapel:review:begin -->";
pub const END: &str = "<!-- stapel:review:end -->";

const NOTE: &str = "Generated by stapel; edits between the markers are overwritten.";

fn text<'a>(m: &'a Map<String, Value>, name: &str) -> Option<&'a str> {
    m.get(name).and_then(Value::as_str)
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

/// The order of a round: whole numbers first, ascending, then other text.
fn round_key(round: Option<&Value>) -> (u8, u64, String) {
    match round {
        Some(v) => match whole_round(v) {
            Some(n) => (0, n, String::new()),
            None => (1, 0, v.as_str().map(str::to_string).unwrap_or_else(|| v.to_string())),
        },
        None => (2, 0, String::new()),
    }
}

fn round_text(round: Option<&Value>) -> String {
    match round {
        Some(Value::String(s)) => s.clone(),
        Some(v) => v.to_string(),
        None => String::new(),
    }
}

#[derive(Default)]
struct Row {
    round: String,
    roles: BTreeSet<String>,
    severities: [u64; 3],
    falses: u64,
    fates: BTreeMap<String, u64>,
}

/// The check runs: one row per level with the newest record of that level, or `Check runs: none`.
/// A record without `level` is of level `head`.
fn run_rows(runs: &[Map<String, Value>]) -> String {
    let mut newest: [Option<&Map<String, Value>>; 3] = [None; 3];
    for m in runs.iter().filter(|m| text(m, "kind") == Some("check")) {
        let level = text(m, "level").unwrap_or("head");
        if let Some(i) = LEVELS.iter().position(|l| *l == level) {
            newest[i] = Some(m);
        }
    }
    if newest.iter().all(Option::is_none) {
        return "Check runs: none\n".to_string();
    }
    let mut out = String::from("Check runs:\n\n| Level | Result | Commit | At | Steps |\n|---|---|---|---|---|\n");
    for (level, m) in LEVELS.iter().zip(newest) {
        let Some(m) = m else { continue };
        let commit: String = text(m, "head").unwrap_or("").chars().take(7).collect();
        let mut counts: BTreeMap<&str, u64> = BTreeMap::new();
        if let Some(steps) = m.get("steps").and_then(Value::as_array) {
            for s in steps {
                let outcome = s.get("outcome").and_then(Value::as_str).unwrap_or("");
                *counts.entry(outcome).or_insert(0) += 1;
            }
        }
        let steps = if counts.is_empty() {
            "—".to_string()
        } else {
            let parts: Vec<String> = counts.iter().map(|(o, n)| format!("{o} {n}")).collect();
            parts.join(", ")
        };
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} |\n",
            level,
            cell(text(m, "result").unwrap_or("")),
            cell(&commit),
            cell(text(m, "at").unwrap_or("")),
            cell(&steps),
        ));
    }
    out
}

const LEVELS: [&str; 3] = ["steps", "head", "full"];

/// The block for the findings and the check runs of a ticket: both marker lines included, every
/// line ending in `\n`.
pub fn render(findings: &[Map<String, Value>], runs: &[Map<String, Value>]) -> String {
    let mut rows: BTreeMap<(usize, String, (u8, u64, String)), Row> = BTreeMap::new();
    let mut seen: Vec<&str> = Vec::new();
    for m in findings.iter().filter(|m| !m.contains_key("kind")) {
        let Some(id) = text(m, "id") else { continue };
        if seen.contains(&id) {
            continue;
        }
        seen.push(id);
        let state = state_of(findings, id);
        let Some(finding) = state.finding.as_ref() else {
            continue;
        };
        let stage = text(finding, "stage").unwrap_or("").to_string();
        let rank = STAGES
            .iter()
            .position(|s| *s == stage)
            .unwrap_or(STAGES.len());
        let round = finding.get("round");
        let row = rows
            .entry((rank, stage, round_key(round)))
            .or_insert_with(|| Row {
                round: round_text(round),
                ..Row::default()
            });
        if let Some(role) = text(finding, "role") {
            row.roles.insert(role.to_string());
        }
        if state.verdict.as_deref() == Some("false") {
            row.falses += 1;
        } else if let Some(i) = ["HIGH", "MEDIUM", "LOW"]
            .iter()
            .position(|s| Some(*s) == state.severity.as_deref())
        {
            row.severities[i] += 1;
        }
        if let Some(fate) = state.fate {
            *row.fates.entry(fate).or_insert(0) += 1;
        }
    }

    let mut out = format!("{BEGIN}\n{NOTE}\n\n");
    if rows.is_empty() {
        out.push_str("Findings: none\n");
    } else {
        out.push_str("Findings:\n\n");
        out.push_str("| Stage | Round | Roles | HIGH | MEDIUM | LOW | False | Fates |\n");
        out.push_str("|---|---|---|---|---|---|---|---|\n");
        for ((_, stage, _), row) in &rows {
            let roles: Vec<&str> = row.roles.iter().map(String::as_str).collect();
            let fates: Vec<String> = row.fates.iter().map(|(f, n)| format!("{f} {n}")).collect();
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} | {} | {} |\n",
                cell(stage),
                cell(&row.round),
                cell(&roles.join(", ")),
                row.severities[0],
                row.severities[1],
                row.severities[2],
                row.falses,
                cell(&fates.join(", ")),
            ));
        }
    }
    out.push('\n');
    out.push_str(&run_rows(runs));
    out.push_str(END);
    out.push('\n');
    out
}

fn is_marker(line: &str, marker: &str) -> bool {
    let line = line.strip_suffix('\n').unwrap_or(line);
    let line = line.strip_suffix('\r').unwrap_or(line);
    line.trim_end_matches(' ') == marker
}

fn ending(line: &str) -> &'static str {
    if line.ends_with("\r\n") { "\r\n" } else { "\n" }
}

/// Where the block goes in a `ticket.md` text.
struct Spot {
    /// The lines of the text, with their line ends.
    lines: Vec<String>,
    /// The line of the Review heading.
    heading: usize,
    /// One past the last line of the Review section.
    end: usize,
    /// The begin and end marker lines of the block in the section.
    block: Option<(usize, usize)>,
}

/// The Review section and its block; `Ok(None)` when the text has no Review section.
fn locate(text: &str) -> Result<Option<Spot>, String> {
    let lines: Vec<String> = text.split_inclusive('\n').map(str::to_string).collect();
    let scanned = ticket::scan(text);
    if scanned.len() < lines.len() {
        return Err("a carriage return alone ends a line".into());
    }
    let headings: Vec<usize> = (0..lines.len())
        .filter(|i| matches!(&scanned[*i].heading, Some((2, _))))
        .collect();
    let reviews: Vec<usize> = headings
        .iter()
        .copied()
        .filter(|i| {
            matches!(&scanned[*i].heading, Some((_, t)) if t.trim().eq_ignore_ascii_case("review"))
        })
        .collect();
    if reviews.len() > 1 {
        return Err("has two Review sections".into());
    }
    let Some(&heading) = reviews.first() else {
        return Ok(None);
    };
    let end = headings
        .iter()
        .copied()
        .find(|i| *i > heading)
        .unwrap_or(lines.len());
    let begins: Vec<usize> = (heading + 1..end)
        .filter(|i| is_marker(&lines[*i], BEGIN))
        .collect();
    let ends: Vec<usize> = (heading + 1..end)
        .filter(|i| is_marker(&lines[*i], END))
        .collect();
    let block = match (begins.as_slice(), ends.as_slice()) {
        ([], []) => None,
        ([b], [e]) if b < e => Some((*b, *e)),
        ([_], [_]) => return Err("the end marker of the generated block comes first".into()),
        _ if begins.len() > 1 || ends.len() > 1 => {
            return Err("has two generated blocks or an unpaired marker".into());
        }
        ([], _) => return Err("the end marker of the generated block has no begin marker".into()),
        _ => return Err("the begin marker of the generated block has no end marker".into()),
    };
    Ok(Some(Spot {
        lines,
        heading,
        end,
        block,
    }))
}

/// Whether the block can be placed in `ticket_text`: a Review section with no broken markers, or no
/// Review section at all.
pub fn can_place(ticket_text: &str) -> Result<(), String> {
    locate(ticket_text).map(|_| ())
}

/// `ticket_text` with `block` (from `render`) in its Review section: the lines of an existing block
/// are replaced; else the block follows the last non-empty line of the section after one empty
/// line. A text with no Review section comes back unchanged.
pub fn place(ticket_text: &str, block: &str) -> Result<String, String> {
    let Some(spot) = locate(ticket_text)? else {
        return Ok(ticket_text.to_string());
    };
    let Spot {
        mut lines,
        heading,
        end,
        block: old,
    } = spot;
    let eol = match old {
        Some((begin, _)) => ending(&lines[begin]),
        None => lines.first().map_or("\n", |l| ending(l)),
    };
    let mut new = block.replace('\n', eol);
    match old {
        Some((begin, last)) => {
            if !lines[last].ends_with('\n') {
                new.truncate(new.len() - eol.len());
            }
            lines.splice(begin..=last, [new]);
        }
        None => {
            let after = (heading..end)
                .rev()
                .find(|i| *i == heading || !lines[*i].trim().is_empty())
                .expect("the heading line exists");
            if !lines[after].ends_with('\n') {
                lines[after].push_str(eol);
            }
            lines.insert(after + 1, format!("{eol}{new}"));
        }
    }
    Ok(lines.concat())
}

/// The text with CRLF read as LF and its generated block removed, with the one empty line right
/// before the begin marker; `None` when the markers are broken or the text has two Review sections.
pub fn without_block(text: &str) -> Option<String> {
    let text = text.replace("\r\n", "\n");
    let Some(spot) = locate(&text).ok()? else {
        return Some(text);
    };
    let Some((begin, last)) = spot.block else {
        return Some(text);
    };
    let from = if begin > spot.heading + 1 && spot.lines[begin - 1].trim().is_empty() {
        begin - 1
    } else {
        begin
    };
    let mut lines = spot.lines;
    lines.drain(from..=last);
    Some(lines.concat())
}

/// The body of a Review section without its generated block; the body itself when the markers are
/// broken.
pub fn body_without_block(body: &str) -> String {
    let wrapped = format!("## Review\n{body}");
    match without_block(&wrapped) {
        Some(text) => text
            .strip_prefix("## Review\n")
            .map_or_else(|| body.to_string(), str::to_string),
        None => body.to_string(),
    }
}

/// Whether the block of the ticket folder `dir` can be written: `Ok(true)` with a Review section and
/// whole markers, `Ok(false)` with no `ticket.md` or no Review section, `Err` with `<path>: <reason>`
/// for broken markers or two Review sections. It writes nothing.
pub fn guard(dir: &Path) -> Result<bool, String> {
    let path = dir.join("ticket.md");
    if std::fs::symlink_metadata(&path).is_err() {
        return Ok(false);
    }
    let text = ticket::read(&path)?;
    let spot = locate(&text).map_err(|r| format!("{}: {r}", path.display()))?;
    Ok(spot.is_some())
}

/// The block of a ticket folder, from its `findings.jsonl` and `runs.jsonl`.
fn render_folder(dir: &Path) -> Result<String, String> {
    let read = |name: &str| -> Result<Vec<Map<String, Value>>, String> {
        Ok(journal::read(&dir.join(name))?
            .into_iter()
            .filter_map(|(_, e)| match e {
                Entry::V1(m) | Entry::Legacy(m) => Some(m),
                Entry::Problem(_) => None,
            })
            .collect())
    };
    Ok(render(&read("findings.jsonl")?, &read("runs.jsonl")?))
}

/// Rewrites the block in the `ticket.md` of the ticket folder `dir` through a temporary file in the
/// folder and a rename. `Ok(false)` when there is no `ticket.md` or no Review section: nothing is
/// written.
pub fn write(dir: &Path) -> Result<bool, String> {
    let path = dir.join("ticket.md");
    if std::fs::symlink_metadata(&path).is_err() {
        return Ok(false);
    }
    let old = ticket::read(&path)?;
    let label = |reason: String| format!("{}: {reason}", path.display());
    if locate(&old).map_err(label)?.is_none() {
        return Ok(false);
    }
    let new = place(&old, &render_folder(dir)?).map_err(|r| format!("{}: {r}", path.display()))?;
    if new == old {
        return Ok(true);
    }
    let temp = dir.join(format!(".ticket.md.{}.tmp", std::process::id()));
    std::fs::write(&temp, &new)
        .and_then(|()| std::fs::rename(&temp, &path))
        .map_err(|e| {
            let _ = std::fs::remove_file(&temp);
            format!("{}: {e}", path.display())
        })?;
    Ok(true)
}
